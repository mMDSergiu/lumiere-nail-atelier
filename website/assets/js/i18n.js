export const STRINGS = { en, ro, ru };

/** Keys the salon may edit (everything except interface and editor labels). */
export const EDITABLE_KEYS = Object.keys(en).filter((k) => !/^(ui|admin|shape|length)\./.test(k));

export function toLang(value) {
  const v = String(value ?? '').toLowerCase().slice(0, 2);
  return v === 'ro' || v === 'ru' ? v : 'en';
}

/** Translator for one language, with the salon's own text overrides on top. */
export function createT(lang, overrides = {}) {
  const base = STRINGS[lang] ?? en;
  return (key, vars) => {
    let out = overrides[key] || base[key] || en[key] || key;
    if (vars) for (const [k, v] of Object.entries(vars)) out = out.replace(`{${k}}`, () => String(v));
    return out;
  };
}
