const DICTS: Record<Lang, Record<string, string>> = { en: {}, ro: RO, ru: RU };

export function toLang(value: string | null | undefined): Lang {
  const v = (value ?? '').toLowerCase().slice(0, 2);
  return v === 'ro' || v === 'ru' ? v : 'en';
}

export function makeTranslator(lang: Lang): Translate {
  const dict = DICTS[lang];
  return (text, vars) => {
    let out = dict[text] ?? text;
    if (vars) for (const [k, v] of Object.entries(vars)) out = out.replace(`{${k}}`, () => String(v));
    return out;
  };
}
